// Helper to generate a realistic workbook page mockup SVG as data URL
function createMockPageSvg(pageTitle: string, pageNum: string, problems: { num: number; correct: boolean; studentAns: string }[]) {
  const problemRows = problems
    .map((p, idx) => {
      const y = 90 + idx * 45;
      const mark = p.correct
        ? `<circle cx="45" cy="${y}" r="16" fill="none" stroke="#22c55e" stroke-width="3" stroke-dasharray="3 1" />`
        : `<path d="M35 ${y - 12} L55 ${y + 12} M55 ${y - 12} L35 ${y + 12}" stroke="#ef4444" stroke-width="4" stroke-linecap="round" />`;
      return `
        <g>
          ${mark}
          <text x="75" y="${y + 5}" font-family="sans-serif" font-weight="bold" font-size="14" fill="#1e293b">[${p.num}번]</text>
          <text x="125" y="${y + 5}" font-family="sans-serif" font-size="13" fill="#64748b">학생 마킹: ${p.studentAns}</text>
          <line x1="75" y1="${y + 18}" x2="340" y2="${y + 18}" stroke="#e2e8f0" stroke-width="1" stroke-dasharray="2 2" />
        </g>
      `;
    })
    .join('');

  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 380 480" width="380" height="480">
      <defs>
        <filter id="shadow" x="-5%" y="-5%" width="110%" height="110%">
          <feDropShadow dx="0" dy="4" stdDeviation="6" flood-opacity="0.1" />
        </filter>
      </defs>
      <rect width="380" height="480" fill="#ffffff" rx="10" filter="url(#shadow)" stroke="#cbd5e1" stroke-width="1" />
      <rect x="0" y="0" width="380" height="42" fill="#f8fafc" rx="10" />
      <rect x="0" y="32" width="380" height="10" fill="#f8fafc" />
      <line x1="0" y1="42" x2="380" y2="42" stroke="#e2e8f0" stroke-width="1" />
      
      <text x="20" y="26" font-family="sans-serif" font-weight="bold" font-size="13" fill="#0f172a">${pageTitle}</text>
      <text x="320" y="26" font-family="sans-serif" font-weight="bold" font-size="12" fill="#6366f1">${pageNum}</text>
      
      ${problemRows}
      
      <line x1="20" y1="440" x2="360" y2="440" stroke="#e2e8f0" stroke-width="1" />
      <text x="20" y="460" font-family="sans-serif" font-size="11" fill="#94a3b8">ScoreCompass AI Smart OCR Auto-Grading Sheet</text>
      <text x="330" y="460" font-family="sans-serif" font-size="11" fill="#94a3b8">${pageNum}</text>
    </svg>
  `;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

